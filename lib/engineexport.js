/**
 * 精灵表导出成引擎能直接吃的格式。
 *
 * 为什么需要：我们自己那套 `<名字>.json` 是**引擎无关的**，但用户拿到它还得自己写
 * Unity 的切图 .meta、Godot 的 SpriteFrames、Cocos 的 plist —— 这一步每次都要重做，
 * 而且坐标系很容易搞反（Unity 左下原点、Godot 左上原点、Cocos 纹理坐标左下原点）。
 *
 * 三种格式：
 *   unity   .meta（TextureImporter + spriteSheet.sprites 多图切片）
 *   godot   .tres（SpriteFrames + AtlasTexture 子资源，一动画一组 frames）
 *   cocos   .plist（TexturePacker format 3，Cocos 能直接读）
 *
 * 诚实的边界：这三个文件都是**按格式规范生成的最佳努力**，我没有在真实引擎里导入验证过
 * （机器上没装 Unity/Godot）。格式对不对可以静态保证，但"导入后行为如何"需要你在引擎里确认。
 */
import { createHash } from 'node:crypto'

/** 稳定 guid（Unity 用 32 位十六进制）。 */
function stableGuid(seed, len = 32) {
  return createHash('md5').update(String(seed)).digest('hex').slice(0, len)
}

/** 每帧的名字：<动画名>_<序号>。 */
function frameNames(animation) {
  const count = animation.grid?.count ?? animation.frames?.length ?? 0
  return Array.from({ length: count }, (_, i) => `${animation.name}_${i}`)
}

/** 每帧的矩形（sheet 左上原点）。 */
function frameRects(animation) {
  const cell = animation.cell
  const columns = animation.grid?.columns ?? 1
  const count = animation.grid?.count ?? animation.frames?.length ?? 0
  return Array.from({ length: count }, (_, i) => ({
    index: i,
    x: (i % columns) * cell.w,
    y: Math.floor(i / columns) * cell.h,
    w: cell.w,
    h: cell.h,
  }))
}

/**
 * Unity 的 .meta（多图切片）。
 * @param {{animation:object, guid?:string, pixelsPerUnit?:number}} params
 */
export function toUnityMeta({ animation, guid = null, pixelsPerUnit = 100 } = {}) {
  const sheetGuid = guid ?? stableGuid(`${animation.image}|${animation.grid?.count}`)
  const names = frameNames(animation)
  const rects = frameRects(animation)
  const pivot = Array.isArray(animation.pivot) ? animation.pivot : [0.5, 1]
  const sprites = rects.map((rect, i) => [
    '    - serializedVersion: 2',
    `      name: ${names[i]}`,
    '      rect:',
    '        serializedVersion: 2',
    `        x: ${rect.x}`,
    // Unity 的 rect 原点是**左下**，而精灵表坐标是左上 → y 要翻
    `        y: ${(animation.imageSize?.[1] ?? 0) - rect.y - rect.h}`,
    `        width: ${rect.w}`,
    `        height: ${rect.h}`,
    '      alignment: 0',
    `      pivot: {x: ${pivot[0]}, y: ${pivot[1] === 1 ? 0 : 1 - pivot[1]}}`,
    '      border: {x: 0, y: 0, z: 0, w: 0}',
    '      outline: []',
    '      physicsShape: []',
    '      tessellationDetail: 0',
    '      bones: []',
    `      spriteID: ${stableGuid(`${sheetGuid}|${i}`)}`,
    `      internalID: ${i + 1}`,
    '      vertices: []',
    '      indices: ',
    '      edges: []',
    '      weights: []',
  ].join('\n')).join('\n')

  return `fileFormatVersion: 2
guid: ${sheetGuid}
TextureImporter:
  internalIDToNameTable: []
  externalObjects: {}
  serializedVersion: 12
  mipmaps:
    mipMapMode: 0
    enableMipMap: 0
    sRGBTexture: 1
    linearTexture: 0
  isReadable: 0
  streamingMipmaps: 0
  textureFormat: 1
  maxTextureSize: 2048
  textureSettings:
    serializedVersion: 2
    filterMode: 0
    aniso: 1
    mipBias: 0
    wrapU: 1
    wrapV: 1
  nPOTScale: 0
  lightmap: 0
  compressionQuality: 50
  spriteMode: 2
  spriteExtrude: 1
  spriteMeshType: 1
  alignment: 0
  spritePivot: {x: ${pivot[0]}, y: ${pivot[1] === 1 ? 0 : 1 - pivot[1]}}
  spritePixelsToUnits: ${pixelsPerUnit}
  spriteBorder: {x: 0, y: 0, z: 0, w: 0}
  spriteGenerateFallbackPhysicsShape: 1
  alphaUsage: 1
  alphaIsTransparency: 1
  spriteTessellationDetail: -1
  textureType: 8
  textureShape: 1
  singleChannelComponent: 0
  flipbookRows: 1
  flipbookColumns: 1
  maxTextureSizeSet: 0
  compressionQualitySet: 0
  textureFormatSet: 0
  ignorePngGamma: 0
  applyGammaDecoding: 0
  platformSettings: []
  spriteSheet:
    serializedVersion: 2
    sprites:
${sprites}
    outline: []
    physicsShape: []
    bones: []
    spriteID: 
    internalID: 0
    vertices: []
    indices: 
    edges: []
    weights: []
  spritePackingTag: 
  pSDRemoveMatte: 0
  pSDShowRemoveMatteOption: 0
  userData: ${JSON.stringify({
    animation: animation.name,
    fps: animation.fps,
    loop: animation.loop !== false,
    frames: animation.grid?.count ?? 0,
    note: 'generated by dsh-gpt-image; frame order = row-major',
  })}
  assetBundleName: 
  assetBundleVariant: 
`
}

/**
 * Godot 4 的 SpriteFrames（.tres）。
 * @param {{animation:object, texturePath?:string}} params
 */
export function toGodotSpriteFrames({ animation, texturePath = null } = {}) {
  const texture = texturePath ?? animation.image
  const names = frameNames(animation)
  const rects = frameRects(animation)
  const fps = Number(animation.fps) || 8
  const loop = animation.loop !== false
  const subResources = rects.map((rect, i) => `[sub_resource type="AtlasTexture" id="AtlasTexture_${i}"]
atlas = ExtResource("1_sheet")
region = Rect2(${rect.x}, ${rect.y}, ${rect.w}, ${rect.h})`).join('\n\n')
  const frames = rects.map((_, i) => `{\n"duration": 1.0,\n"texture": SubResource("AtlasTexture_${i}")\n}`).join(', ')
  return `[gd_resource type="SpriteFrames" load_steps=${rects.length + 2} format=3]

[ext_resource type="Texture2D" path="${texture}" id="1_sheet"]

${subResources}

[resource]
animations = [{
"frames": [${frames}],
"loop": ${loop ? 'true' : 'false'},
"name": &"${animation.name}",
"speed": ${fps}.0
}]
`
}

/**
 * Cocos 的 .plist（TexturePacker format 3）。注意 frame 的 y 是**纹理坐标（左下原点）**。
 * @param {{animation:object, textureFileName?:string}} params
 */
export function toCocosPlist({ animation, textureFileName = null } = {}) {
  const sheetW = animation.imageSize?.[0] ?? 0
  const sheetH = animation.imageSize?.[1] ?? 0
  const names = frameNames(animation)
  const rects = frameRects(animation)
  const entries = rects.map((rect, i) => {
    const bottomY = sheetH - rect.y - rect.h
    return `    <key>${names[i]}.png</key>
    <dict>
      <key>frame</key><string>{{${rect.x},${bottomY}},{${rect.w},${rect.h}}}</string>
      <key>offset</key><string>{0,0}</string>
      <key>rotated</key><false/>
      <key>sourceColorRect</key><string>{{0,0},{${rect.w},${rect.h}}}</string>
      <key>sourceSize</key><string>{${rect.w},${rect.h}}</string>
    </dict>`
  }).join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>frames</key>
  <dict>
${entries}
  </dict>
  <key>metadata</key>
  <dict>
    <key>format</key><integer>3</integer>
    <key>size</key><string>{${sheetW},${sheetH}}</string>
    <key>textureFileName</key><string>${textureFileName ?? animation.image}</string>
    <key>realTextureFileName</key><string>${textureFileName ?? animation.image}</string>
  </dict>
</dict>
</plist>
`
}

/** 支持的引擎。 */
export const ENGINES = ['unity', 'godot', 'cocos']

/**
 * 生成某个引擎需要的文件清单。
 * @returns {{ok:boolean, files?:Array<{name:string, content:string}>, error?:string}}
 */
export function exportForEngine({ animation, engine, texturePath = null }) {
  if (!animation?.image || !animation?.cell || !animation?.grid) {
    return { ok: false, error: '描述文件缺少 image / cell / grid，无法导出' }
  }
  if (engine === 'unity') {
    return { ok: true, files: [{ name: `${animation.image}.meta`, content: toUnityMeta({ animation }) }] }
  }
  if (engine === 'godot') {
    return { ok: true, files: [{ name: `${animation.name}.tres`, content: toGodotSpriteFrames({ animation, texturePath }) }] }
  }
  if (engine === 'cocos') {
    return { ok: true, files: [{ name: `${animation.name}.plist`, content: toCocosPlist({ animation }) }] }
  }
  return { ok: false, error: `不认识的引擎「${engine}」，可用：${ENGINES.join(' / ')}` }
}
